"""`canary report`: run the LOCAL simulation for both releases, write docs/results.md and charts.

Everything in the output comes from this run: offline model metrics on a synthetic test set, the
window-by-window canary analysis for v2-good and v2-bad, and a drift example. All of it is
synthetic data and an in-process simulation, and the page says so.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from .analysis import Thresholds
from .data import generate
from .drift import DriftRow, drift_report
from .model import VERSIONS, ModelBundle, train_all
from .rollout import Outcome, RolloutResult
from .simulate import simulate

SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, GREY = "#2a78d6", "#b7b7b2"
LABEL = "Synthetic data, local in-process simulation (no cluster)"


@dataclass
class Report:
    bundles: dict[str, ModelBundle]
    rollouts: dict[str, RolloutResult]
    drift: dict[str, list[DriftRow]]
    limits: Thresholds
    requests_per_window: int


def build(
    seed: int = 42, requests_per_window: int = 500, bundles: dict[str, ModelBundle] | None = None
) -> Report:
    bundles = bundles or train_all(seed)
    limits = Thresholds()
    rollouts = {
        v: simulate(bundles, v, limits=limits, requests_per_window=requests_per_window, seed=seed)[
            0
        ]
        for v in ("v2-good", "v2-bad")
    }
    ref = bundles["v1"]
    drift = {}
    for name, shift in (("same population", 0.0), ("shifted cohort (shift=1.0)", 1.0)):
        current = generate(2000, seed=seed + 7, shift=shift)
        scores = ref.estimator.predict_proba(current.X)[:, 1]
        drift[name] = drift_report(ref.reference_X, ref.reference_scores, current.X, scores)
    return Report(bundles, rollouts, drift, limits, requests_per_window)


def _ms(value: float) -> str:
    return "n/a" if math.isnan(value) else f"{value * 1000:.1f}"


def results_markdown(r: Report) -> str:
    t = r.limits
    lines = [
        "# Results",
        "",
        f"**{LABEL}.** Generated by `canary report`. The effects are planted on purpose: v2-bad",
        "ships v2-good's weights with a feature-order bug and a missing divide-by-zero guard.",
        "Latency is measured inside one Python process, so it only shows the check runs.",
        "",
        "## Offline metrics (synthetic test set, 3,000 students, scored through the serving code)",
        "",
        "| Model | ROC AUC | Requests that fail (HTTP 500) | Mean predicted risk |",
        "| --- | --- | --- | --- |",
    ]
    for v in VERSIONS:
        m = r.bundles[v].metrics
        lines.append(f"| {v} | {m['auc']:.3f} | {m['error_rate']:.1%} | {m['mean_score']:.3f} |")
    lines += [
        "",
        "## Canary rollout, window by window",
        "",
        f"Stable = v1, 10 replicas, {t.min_requests} requests per side before any decision. "
        f"Fail if canary error rate > stable + {t.error_rate_margin:.0%}, prediction PSI > "
        f"{t.max_score_psi}, or p95 latency > {t.latency_ratio}x stable and "
        f"+{t.latency_slack_s * 1000:.0f} ms.",
        "",
    ]
    for version, res in r.rollouts.items():
        lines += [
            f"### {version}: **{res.outcome.value.replace('_', ' ')}** ({res.reason})",
            "",
            "| Step | Window | Stable req. | Canary req. | Canary errors | Stable errors "
            "| p95 ms (stable / canary) | Prediction PSI | Decision |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for w in res.windows:
            c = w.verdict.comparison
            lines.append(
                f"| {w.step_percent}% | {w.window} | {c.stable_requests:.0f} | "
                f"{c.canary_requests:.0f} | {c.canary_error_rate:.2%} | {c.stable_error_rate:.2%} "
                f"| {_ms(c.stable_p95_s)} / {_ms(c.canary_p95_s)} | {c.score_psi:.3f} | "
                f"{w.verdict.action.value} |"
            )
        lines.append("")
    lines += [
        "## Input and output drift vs the v1 training reference (`canary drift`)",
        "",
        "| Feature | PSI, same population | Status | PSI, shifted cohort | Status |",
        "| --- | --- | --- | --- | --- |",
    ]
    same, shifted = r.drift.values()
    for a, b in zip(same, shifted, strict=True):
        lines.append(f"| {a.name} | {a.psi:.3f} | {a.status} | {b.psi:.3f} | {b.status} |")
    lines += ["", "PSI rule of thumb: < 0.1 ok, 0.1-0.25 warn, > 0.25 alert.", ""]
    return "\n".join(lines)


def _style(ax, title: str | None = None, subtitle: str | None = None) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)
    if title:
        ax.set_title(title, loc="left", fontsize=12.5, fontweight="bold", color=INK, pad=24)
    if subtitle:
        ax.text(0, 1.03, subtitle, transform=ax.transAxes, fontsize=9.5, color=INK_2)


def _timeline(res: RolloutResult) -> tuple[list[int], list[int]]:
    """Canary traffic share per window, plus one final point for the end state."""
    xs = list(range(1, len(res.windows) + 1))
    ys = [w.step_percent for w in res.windows]
    xs.append(len(xs) + 1)
    ys.append(100 if res.outcome is Outcome.PROMOTED else 0)
    return xs, ys


def plot_timeline(r: Report, path: Path) -> None:
    import matplotlib.pyplot as plt

    good, bad = r.rollouts["v2-good"], r.rollouts["v2-bad"]
    fig, ax = plt.subplots(figsize=(10, 4.2), dpi=150)
    fig.set_facecolor(SURFACE)
    for res, color, style, name in ((good, GREY, "--", "v2-good"), (bad, BLUE, "-", "v2-bad")):
        xs, ys = _timeline(res)
        ax.step(xs, ys, where="post", color=color, linewidth=2.2, linestyle=style)
        ax.plot(xs[:-1], ys[:-1], "o", color=color, markersize=6)
        end = "promoted to 100%" if res.outcome is Outcome.PROMOTED else "rolled back to 0%"
        ax.annotate(
            f"{name}: {end}",
            (xs[-1], ys[-1]),
            xytext=(8, 6 if ys[-1] else 8),
            textcoords="offset points",
            fontsize=9.5,
            color=INK,
        )
    first_fail = next(w for w in bad.windows if w.verdict.action.value == "fail")
    _style(
        ax,
        f"The broken release never got past 10% of traffic; the good one reached 100% "
        f"in {len(good.windows)} windows",
        f"Canary share of traffic per {r.requests_per_window}-request window. "
        f"v2-bad failed at window {bad.windows.index(first_fail) + 1}. {LABEL}.",
    )
    ax.set_ylim(-5, 115)
    ax.set_yticks([0, 10, 50, 100])
    ax.set_yticklabels(["0%", "10%", "50%", "100%"])
    ax.set_xlabel("Analysis window", color=INK_2, fontsize=9)
    last = max(len(good.windows), len(bad.windows)) + 1
    ax.set_xticks(range(1, last + 1))
    ax.set_xlim(0.5, last + 2.2)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def plot_checks(r: Report, path: Path) -> None:
    import matplotlib.pyplot as plt

    t = r.limits
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2), dpi=150)
    fig.set_facecolor(SURFACE)
    metrics = (
        ("Canary error rate, % (limit: stable + 1 pp)", "canary_error_rate", 100, 1.0),
        ("Prediction PSI, canary vs stable", "score_psi", 1, t.max_score_psi),
    )
    for ax, (label, attr, scale, limit) in zip(axes, metrics, strict=True):
        for version, color, style in (("v2-good", GREY, "--"), ("v2-bad", BLUE, "-")):
            res = r.rollouts[version]
            ys = [getattr(w.verdict.comparison, attr) * scale for w in res.windows]
            xs = np.arange(1, len(ys) + 1)
            ax.plot(xs, ys, color=color, linewidth=2, linestyle=style, marker="o", markersize=5)
            ax.annotate(
                version,
                (xs[-1], ys[-1]),
                xytext=(6, 0),
                textcoords="offset points",
                fontsize=9,
                color=INK,
                va="center",
            )
        ax.axhline(limit, color=INK_2, linewidth=1, linestyle=":")
        ax.text(0.6, limit, " limit", color=INK_2, fontsize=8.5, va="bottom")
        _style(ax)
        ax.set_title(label, loc="left", fontsize=10, color=INK)
        ax.set_xlabel("Analysis window", color=INK_2, fontsize=9)
        ax.set_ylim(bottom=0)
        ax.set_xlim(0.5, 7.8)
    bad = r.rollouts["v2-bad"].windows[-1].verdict.comparison
    fig.suptitle(
        f"v2-bad failed two checks at once: {bad.canary_error_rate:.1%} errors and "
        f"prediction PSI {bad.score_psi:.2f}",
        x=0.01,
        ha="left",
        fontsize=12.5,
        fontweight="bold",
        color=INK,
    )
    fig.text(
        0.01,
        0.875,
        f"Values before {t.min_requests} canary requests are shown but not acted on "
        f"(noisy). {LABEL}.",
        fontsize=9.5,
        color=INK_2,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.87))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def write(out_dir: Path, seed: int = 42) -> Report:
    r = build(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "results.md").write_text(results_markdown(r))
    plot_timeline(r, out_dir / "img" / "rollout_timeline.png")
    plot_checks(r, out_dir / "img" / "canary_checks.png")
    return r
